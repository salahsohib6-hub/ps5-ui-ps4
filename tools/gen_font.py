#!/usr/bin/env python3
"""Rasterise the Inter typeface (SIL OFL 1.1) into a small 8-bit alpha atlas
that is compiled into the app as src/gfx/FontData.cpp.

Usage: python3 tools/gen_font.py [--regular PATH --semibold PATH]
Requires Pillow. The generated file is committed, so this is only needed if
you want to change sizes or the typeface.
"""
import argparse, os, sys
from PIL import Image, ImageDraw, ImageFont

FACES = [  # (symbol, style, pixel size)
    ("Small",   "regular",  18),
    ("Body",    "regular",  24),
    ("Heading", "semibold", 32),
    ("Title",   "semibold", 52),
]
FIRST, LAST = 32, 126

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--regular", default="/usr/share/fonts/opentype/inter/Inter-Regular.otf")
    ap.add_argument("--semibold", default="/usr/share/fonts/opentype/inter/Inter-SemiBold.otf")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "src", "gfx", "FontData.cpp"))
    a = ap.parse_args()
    paths = {"regular": a.regular, "semibold": a.semibold}

    out = []
    out.append("// GENERATED by tools/gen_font.py - do not edit by hand.\n")
    out.append("// Glyph bitmaps are rasterised from the Inter typeface\n")
    out.append("// (c) The Inter Project Authors, licensed under the SIL Open Font License 1.1.\n")
    out.append("// See THIRD_PARTY_NOTICES.md.\n")
    out.append('#include "gfx/FontData.h"\n\nnamespace ps5ui {\nnamespace {\n')
    face_syms = []
    for sym, style, px in FACES:
        font = ImageFont.truetype(paths[style], px)
        asc, desc = font.getmetrics()
        data = bytearray()
        glyphs = []
        for cp in range(FIRST, LAST + 1):
            ch = chr(cp)
            adv = font.getlength(ch)
            bbox = font.getbbox(ch, anchor="ls")  # relative to baseline origin
            if ch == " " or bbox[2] <= bbox[0] or bbox[3] <= bbox[1]:
                glyphs.append((round(adv * 16), 0, 0, 0, 0, len(data)))
                continue
            l, t, r, b = bbox
            w, h = r - l, b - t
            img = Image.new("L", (w + 4, h + 4), 0)
            ImageDraw.Draw(img).text((-l + 2, -t + 2), ch, font=font, fill=255, anchor="ls")
            img = img.crop((2, 2, 2 + w, 2 + h))
            off = len(data)
            data.extend(img.tobytes())
            glyphs.append((round(adv * 16), l, -t, w, h, off))
        name = f"kFace{sym}"
        out.append(f"const uint8_t {name}Data[] = {{\n")
        for i in range(0, len(data), 24):
            out.append("  " + ",".join(str(v) for v in data[i:i + 24]) + ",\n")
        if not data:
            out.append("  0\n")
        out.append("};\n")
        out.append(f"const Glyph {name}Glyphs[] = {{\n")
        for (adv, bx, by, w, h, off) in glyphs:
            out.append(f"  {{{adv},{bx},{by},{w},{h},{off}}},\n")
        out.append("};\n")
        face_syms.append((sym, px, asc, asc + desc))
    out.append("}  // namespace\n\n")
    out.append("const FontFace kFontFaces[kFontFaceCount] = {\n")
    for sym, px, asc, lh in face_syms:
        out.append(f"  {{{px}, {asc}, {lh}, kFace{sym}Glyphs, kFace{sym}Data}},\n")
    out.append("};\n\n}  // namespace ps5ui\n")
    with open(a.out, "w") as f:
        f.write("".join(out))
    print("wrote", os.path.normpath(a.out), os.path.getsize(a.out) // 1024, "KiB")

if __name__ == "__main__":
    sys.exit(main())
